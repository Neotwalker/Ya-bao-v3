/**
 * Register the global settings page only when ACF Pro is available.
 */
function yabao_acf_register_global_settings_page(): void {
    if ( ! function_exists( 'acf_add_options_page' ) ) {
        return;
    }

    acf_add_options_page(
        array(
            'page_title' => 'Настройки сайта',
            'menu_title' => 'Настройки сайта',
            'menu_slug'  => 'yabao-global-settings',
            'capability' => 'edit_theme_options',
            'redirect'   => false,
            'position'   => 61,
            'icon_url'   => 'dashicons-admin-generic',
        )
    );
}
add_action( 'acf/init', 'yabao_acf_register_global_settings_page', 5 );

/**
 * Footer menus are separate so an administrator can manage each column
 * independently. No fallback menu is generated by the theme.
 */
function yabao_acf_register_global_menu_locations(): void {
    register_nav_menus(
        array(
