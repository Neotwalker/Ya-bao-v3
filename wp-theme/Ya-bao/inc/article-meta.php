const YABAO_POST_VIEWS_META_KEY = '_yabao_post_views';
const YABAO_POST_VIEW_COOKIE_TTL = 30 * MINUTE_IN_SECONDS;

/**
 * Return the stored number of article views.
 *
 * Missing metadata intentionally means zero.
 */
function yabao_get_post_views( int $post_id ): int {
    if (
        $post_id < 1 ||
        'post' !== get_post_type( $post_id )
    ) {
        return 0;
    }

    $value = get_post_meta(
        $post_id,
        YABAO_POST_VIEWS_META_KEY,
        true
    );

    return max(
        0,
        (int) $value
    );
}

/**
 * Increment a post view count.
 */
function yabao_increment_post_views( int $post_id ): int {
    if (
        $post_id < 1 ||
        'post' !== get_post_type( $post_id )
    ) {
        return 0;
    }

    $views = yabao_get_post_views(
        $post_id
    ) + 1;

    update_post_meta(
        $post_id,
        YABAO_POST_VIEWS_META_KEY,
        $views
    );

    return $views;
}

/**
 * Cookie used to prevent rapid repeated views from the same browser.
 */
function yabao_post_view_cookie_name( int $post_id ): string {
    return 'yabao_post_view_' . $post_id;
}

/**
 * Count one frontend article view per browser every 30 minutes.
 */
function yabao_track_post_view(): void {
    if (
        is_admin() ||
        wp_doing_ajax() ||
        is_preview() ||
        is_feed() ||
        is_embed() ||
        ! is_singular( 'post' )
    ) {
        return;
    }

    if (
        defined( 'REST_REQUEST' ) &&
        REST_REQUEST
    ) {
        return;
    }

    $post_id = (int) get_queried_object_id();

    if (
        $post_id < 1 ||
        'publish' !== get_post_status( $post_id )
    ) {
        return;
    }

    $cookie_name = yabao_post_view_cookie_name(
        $post_id
    );

    if (
        isset( $_COOKIE[ $cookie_name ] ) &&
        '1' === (string) $_COOKIE[ $cookie_name ]
    ) {
        return;
    }

    yabao_increment_post_views(
        $post_id
    );

    $expires = time() +
        YABAO_POST_VIEW_COOKIE_TTL;

    setcookie(
        $cookie_name,
        '1',
        array(
            'expires'  => $expires,
            'path'     => '/',
            'domain'   => '',
            'secure'   => is_ssl(),
            'httponly' => true,
            'samesite' => 'Lax',
        )
    );

    /*
     * Keep the current request in sync too.
     */
    $_COOKIE[ $cookie_name ] = '1';
}
add_action(
    'template_redirect',
    'yabao_track_post_view',
    20
);

